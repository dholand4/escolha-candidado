// Busca termos sem distinguir maiúsculas e sem casar pedaços de outras palavras.
// Termos mais longos vêm primeiro para "licença ambiental" vencer "licenciamento", por exemplo.
const termos = Object.keys(GLOSSARIO).sort((a, b) => b.length - a.length)
const escapar = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const REGEX = new RegExp(`(?<![\\p{L}\\p{N}])(${termos.map(escapar).join('|')})(?![\\p{L}\\p{N}])`, 'giu')
const POR_MINUSCULA = Object.fromEntries(Object.entries(GLOSSARIO).map(([t, d]) => [t.toLowerCase(), d]))

// Divide o texto em pedaços: strings comuns e { termo, definicao } para cada termo do glossário.
export function marcarTermos(texto) {
  const partes = []
  let ultimo = 0
  for (const m of texto.matchAll(REGEX)) {
    if (m.index > ultimo) partes.push(texto.slice(ultimo, m.index))
    partes.push({ termo: m[0], definicao: POR_MINUSCULA[m[0].toLowerCase()] })
    ultimo = m.index + m[0].length
  }
  if (ultimo < texto.length) partes.push(texto.slice(ultimo))
  return partes
}
